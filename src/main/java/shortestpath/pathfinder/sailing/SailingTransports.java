package shortestpath.pathfinder.sailing;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Predicate;
import java.util.zip.CRC32;
import net.runelite.api.Quest;
import shortestpath.WorldPointUtil;
import shortestpath.pathfinder.CollisionMap;
import shortestpath.sailing.SeaArea;
import shortestpath.transport.Transport;
import shortestpath.transport.TransportType;

/**
 * Sailing the player's own boat from one mooring to another, as transports: one per boat kind and pair of moorings,
 * from the first mooring's land tile to the second's. A boat leaving a berth always sets out the same way, so how long
 * the leg takes doesn't depend on how the player got there, and each leg can be timed once, over the whole sea, and
 * routed like any other transport. Its duration is boarding, the leg at {@link #SPEED}, and stepping off.
 * <p>
 * The transport files ({@link #resource}) are generated by {@code SailingTimesGenerator}. Their {@link #fingerprint}
 * names the collision map, moorings, speed and search rules they were made from, so a test catches a stale file.
 * Whether the player has the boat at the mooring is not in the files: {@link #usable} checks it per account.
 * <p>
 * Each leg is timed for a boat of its kind with every part it can be fitted with, at {@link #SPEED}, and its row
 * names the restricted {@link SeaArea}s the leg sails through ({@code Sea areas}). For a boat with the parts for them
 * at that speed the row's time is the leg's own ({@link #timedFor}). For a boat with fewer parts it is a lower bound,
 * since keeping out of water only makes a leg longer; for one at another speed the bound is the straight line
 * ({@link #boundFor}).
 * The route then sails such a leg for the boat itself, once the search wants it ({@code SailingSeaEnds}), so the
 * files grow with the moorings, not with the ways a boat can be fitted out.
 */
public final class SailingTransports
{
	/** The boats' base speed the legs are timed at, in tiles per tick. */
	public static final double SPEED = SailingMoves.ESTIMATED_SPEED;
	// Bump when the sailing search's rules change, so the files are made again
	private static final int SEARCH_VERSION = 4;
	static final String FINGERPRINT = "# Fingerprint: ";
	private static volatile Map<Integer, SailingMooring> mooringsByLand;

	private SailingTransports()
	{
	}

	/** The transport type for sailing boats of {@code kind}. */
	public static TransportType type(SailingVessel.Kind kind)
	{
		switch (kind)
		{
			case RAFT:
				return TransportType.SAILING_RAFT;
			case SKIFF:
				return TransportType.SAILING_SKIFF;
			default:
				return TransportType.SAILING_SLOOP;
		}
	}

	/** The boat kind a sailing transport type sails, or {@code null} for any other type. */
	public static SailingVessel.Kind kind(TransportType type)
	{
		if (type == TransportType.SAILING_RAFT) return SailingVessel.Kind.RAFT;
		if (type == TransportType.SAILING_SKIFF) return SailingVessel.Kind.SKIFF;
		if (type == TransportType.SAILING_SLOOP) return SailingVessel.Kind.SLOOP;
		return null;
	}

	/** The resource holding the transports for boats of {@code kind}. */
	public static String resource(SailingVessel.Kind kind)
	{
		return type(kind).getResourcePath();
	}

	/** The mooring whose land tile is {@code landTile}, or {@code null}. */
	public static SailingMooring mooringAt(int landTile)
	{
		Map<Integer, SailingMooring> byLand = mooringsByLand;
		if (byLand == null)
		{
			byLand = new HashMap<>();
			for (SailingMooring mooring : SailingMoorings.all()) byLand.putIfAbsent(mooring.landTile(), mooring);
			mooringsByLand = byLand;
		}
		return byLand.get(landTile);
	}

	/** The mooring a sailing transport boards at, or {@code null} for any other transport. */
	public static SailingMooring from(Transport transport)
	{
		return kind(transport.getType()) == null ? null : mooringAt(transport.getOrigin());
	}

	/** The mooring a sailing transport docks at, or {@code null} for any other transport. */
	public static SailingMooring to(Transport transport)
	{
		return kind(transport.getType()) == null ? null : mooringAt(transport.getDestination());
	}

	/**
	 * Whether the account can sail {@code transport}: it has a boat of the transport's kind available at the mooring it
	 * boards at, which can get from where it casts off there to where it docks at the other by water its parts let
	 * it into ({@link SailingWaters#connects}). The moorings'
	 * levels and finished quests are the transport's own requirements; the quests they need only started,
	 * {@code started} answers.
	 */
	public static boolean usable(Transport transport, SailingFleet fleet, CollisionMap map, SailingWaters waters,
		Predicate<Quest> started)
	{
		SailingMooring from = mooringAt(transport.getOrigin()), to = mooringAt(transport.getDestination());
		SailingVessel vessel = vessel(transport, fleet);
		if (vessel == null || !waters.sails(map, vessel, from, to)) return false;
		for (Quest quest : from.questsStarted())
		{
			if (!started.test(quest)) return false;
		}
		for (Quest quest : to.questsStarted())
		{
			if (!started.test(quest)) return false;
		}
		return true;
	}

	/** The account's boat that sails {@code transport}: one of its kind available where it boards, or {@code null}. */
	public static SailingVessel vessel(Transport transport, SailingFleet fleet)
	{
		SailingVessel.Kind kind = kind(transport.getType());
		SailingMooring from = mooringAt(transport.getOrigin()), to = mooringAt(transport.getDestination());
		if (kind == null || from == null || to == null || fleet == null) return null;
		SailingVessel cheapest = null;
		for (SailingVessel vessel : fleet.vessels())
		{
			if (vessel.kind() == kind && fleet.locations().moored(from, vessel)
				&& (cheapest == null || fleet.recoveryCost(from, vessel) < fleet.recoveryCost(from, cheapest)))
			{
				cheapest = vessel;
			}
		}
		return cheapest;
	}

	/**
	 * Whether {@code transport}'s duration is how long {@code vessel} takes: the boat sails at the speed the leg was
	 * timed at, with the parts for the areas it sails through. Otherwise the duration only bounds it.
	 */
	public static boolean timedFor(Transport transport, SailingVessel vessel)
	{
		return vessel.speed() == SPEED && vessel.areas().containsAll(transport.getSeaAreas());
	}

	/**
	 * {@code transport} with a duration no more than {@code vessel} takes. With fewer parts it is the transport itself:
	 * keeping out of water only makes a leg longer. At another speed the moves themselves change (each tick's velocity
	 * is rounded to quarter tiles), so the time at {@link #SPEED} says nothing sure about the boat's; the bound is then
	 * the straight line between the berths, less the docking range at each end (the boat casts off and docks within
	 * it), at the boat's top speed, as for every other leg sailed for a query.
	 */
	public static Transport boundFor(Transport transport, SailingVessel vessel)
	{
		if (vessel.speed() == SPEED) return transport;
		SailingMooring from = mooringAt(transport.getOrigin()), to = mooringAt(transport.getDestination());
		double tiles = Math.hypot(
			WorldPointUtil.unpackWorldX(from.berthTile()) - WorldPointUtil.unpackWorldX(to.berthTile()),
			WorldPointUtil.unpackWorldY(from.berthTile()) - WorldPointUtil.unpackWorldY(to.berthTile()));
		int sailed = (int) Math.floor(Math.max(0, tiles - 2 * SailingMooring.DOCKING_RANGE) / topSpeed(vessel.moves()));
		return transport.withDuration(SailingMooring.BOARD_TICKS + sailed + SailingMooring.DISEMBARK_TICKS);
	}

	// The farthest any move goes per tick, in a straight line
	static double topSpeed(SailingMoves moves)
	{
		double top = 0;
		for (int move = 0; move < moves.size(); move++)
			top = Math.max(top, Math.hypot(moves.dx(move), moves.dy(move)) / moves.ticks(move));
		return top;
	}

	/** The files' header, for {@code fingerprint}: the column names first, as the transport parser needs. */
	static String header(String fingerprint)
	{
		return "# Origin\tDestination\tSkills\tQuests\tSea areas\tDuration\tDisplay info\n"
			+ "# Sailing the player's own boat between moorings; generated by SailingTimesGenerator, do not edit.\n"
			+ "# Duration: boarding (" + SailingMooring.BOARD_TICKS + " ticks), sailing from the first berth to within"
			+ " docking range of the second at\n"
			+ "# " + SPEED + " tiles per tick with every move ending on sea the hull fits, and stepping off ("
			+ SailingMooring.DISEMBARK_TICKS + " ticks).\n"
			+ "# Skills and Quests: both moorings' docking requirements. Sea areas: the restricted sea areas the leg"
			+ " sails\n# through, with every part the boat can be fitted with.\n"
			+ FINGERPRINT + fingerprint + "\n";
	}

	/** What the files are made from: the collision map, the moorings, the speed and the search's rules. */
	public static String fingerprint(List<SailingMooring> moorings)
	{
		return fingerprint(readBytes("/collision-map.zip"), moorings);
	}

	/**
	 * What the sailing data is made from, in short: the collision map {@code zip} but for its sailing layer (which is
	 * made from it), the moorings, and the speed and version of the search that times the legs.
	 */
	public static String fingerprint(byte[] zip, List<SailingMooring> moorings)
	{
		CRC32 crc = new CRC32();
		java.util.SortedMap<String, byte[]> entries = new java.util.TreeMap<>();
		try (java.util.zip.ZipInputStream in = new java.util.zip.ZipInputStream(new java.io.ByteArrayInputStream(zip)))
		{
			java.util.zip.ZipEntry entry;
			while ((entry = in.getNextEntry()) != null)
			{
				if (!entry.isDirectory() && !entry.getName().startsWith(SailingWaters.LAYER + "/"))
					entries.put(entry.getName(), in.readAllBytes());
			}
		}
		catch (IOException e)
		{
			throw new java.io.UncheckedIOException(e);
		}
		for (Map.Entry<String, byte[]> entry : entries.entrySet())
		{
			crc.update(entry.getKey().getBytes(StandardCharsets.UTF_8));
			crc.update(entry.getValue());
		}
		StringBuilder data = new StringBuilder();
		for (SailingMooring mooring : moorings)
		{
			data.append(mooring.name()).append(mooring.landTile()).append(mooring.berthTile())
				.append(mooring.vessels()).append(mooring.requirements().getSkillLevels())
				.append(mooring.requirements().getQuests()).append('\n');
		}
		data.append(SailingMooring.BOARD_TICKS).append(' ').append(SailingMooring.DISEMBARK_TICKS).append(' ')
			.append(SailingMooring.DOCKING_RANGE);
		crc.update(data.toString().getBytes(StandardCharsets.UTF_8));
		return Long.toHexString(crc.getValue()) + " speed " + SPEED + " search " + SEARCH_VERSION;
	}

	/** The fingerprint a transport file was made with, or {@code null}. */
	static String fingerprintOf(String contents)
	{
		for (String line : contents.split("\n"))
		{
			if (line.startsWith(FINGERPRINT)) return line.substring(FINGERPRINT.length()).trim();
		}
		return null;
	}

	static byte[] readBytes(String path)
	{
		try (InputStream in = SailingTransports.class.getResourceAsStream(path))
		{
			if (in == null) throw new IllegalStateException("missing " + path);
			return in.readAllBytes();
		}
		catch (IOException error)
		{
			throw new IllegalStateException("cannot read " + path, error);
		}
	}
}
