package shortestpath.pathfinder.sailing;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.SortedMap;
import java.util.TreeMap;
import java.util.function.Predicate;
import java.util.zip.CRC32;
import java.util.zip.ZipEntry;
import java.util.zip.ZipInputStream;
import net.runelite.api.Quest;
import shortestpath.pathfinder.CollisionMap;
import shortestpath.sailing.BoatSpeed;
import shortestpath.sailing.LegTimes;
import shortestpath.sailing.SeaArea;
import shortestpath.transport.Transport;

/**
 * Sailing the player's own boat from one mooring to another, as transports: one per boat kind and pair of moorings,
 * from the first mooring's land tile to the second's. A boat leaving a berth always sets out the same way, so how long
 * the leg takes doesn't depend on how the player got there, and each leg can be timed once, over the whole sea, and
 * routed like any other transport. Its duration is boarding, the leg, and stepping off.
 * <p>
 * The transport files ({@link #resource}) are generated by shortest-path-tooling's {@code sailingData} task. Their
 * {@link #fingerprint}
 * names the collision map, moorings, speeds and search rules they were made from, so a test catches a stale file.
 * Whether the player has the boat at the mooring is not in the files: {@link #usable} checks it per account.
 * <p>
 * Each leg is timed for a boat of its kind with every part it can be fitted with, at each base speed a hull gives
 * ({@link LegTimes}), and names the restricted {@link SeaArea}s it sails through at that speed. For a boat at one of
 * those speeds with the parts for them, that time is the leg's own ({@link #timedFor}). For one with fewer parts it is
 * a lower bound, since keeping out of water only makes a leg longer; for a boat at any other speed the bound is the
 * straight line ({@link #boundFor}). The row's {@code Duration} is the fastest of its times and {@code Sea areas}
 * every area it sails through at any of them, so for a boat the account doesn't name the row still bounds the leg.
 * The route sails a bounded leg for the boat itself, once the search wants it ({@code SailingSeaEnds}), so the files
 * grow with the moorings, not with the ways a boat can be fitted out.
 */
public final class SailingTransports
{
	// Bump when the sailing search's rules change, so the files are made again
	private static final int SEARCH_VERSION = 6;
	/** The line of a transport file naming what it was made from ({@link #fingerprint}). */
	public static final String FINGERPRINT = "# Fingerprint: ";
	private static volatile Map<Integer, SailingMooring> mooringsByLand;

	private SailingTransports()
	{
	}

	/** The resource holding the transports for boats of {@code kind}. */
	public static String resource(SailingVessel.Kind kind)
	{
		return kind.transportType().getResourcePath();
	}

	/** The mooring whose land tile is {@code landTile}, or {@code null}. */
	public static SailingMooring mooringAt(int landTile)
	{
		Map<Integer, SailingMooring> byLand = mooringsByLand;
		if (byLand == null)
		{
			byLand = new HashMap<>();
			for (SailingMooring mooring : SailingMoorings.all()) byLand.putIfAbsent(mooring.landTile(), mooring);
			mooringsByLand = byLand;
		}
		return byLand.get(landTile);
	}

	/** The mooring a sailing transport boards at, or {@code null} for any other transport. */
	public static SailingMooring from(Transport transport)
	{
		return transport.getType().isSailing() ? mooringAt(transport.getOrigin()) : null;
	}

	/** The mooring a sailing transport docks at, or {@code null} for any other transport. */
	public static SailingMooring to(Transport transport)
	{
		return transport.getType().isSailing() ? mooringAt(transport.getDestination()) : null;
	}

	/**
	 * Whether {@code vessel} can sail {@code transport}: it can get from where it casts off at the mooring the
	 * transport boards at to where it docks at the other by water its parts let it into
	 * ({@link SailingWaters#connects}), and the account has started the quests both moorings need started. The
	 * moorings' levels and finished quests are the transport's own requirements.
	 */
	public static boolean usable(Transport transport, SailingVessel vessel, CollisionMap map, SailingWaters waters,
		Predicate<Quest> started)
	{
		SailingMooring from = from(transport), to = to(transport);
		if (!sailable(transport, vessel) || !waters.sails(map, vessel, from, to)) return false;
		return from.questsStarted().stream().allMatch(started) && to.questsStarted().stream().allMatch(started);
	}

	/**
	 * The account's boat that sails {@code transport}: the cheapest of its kind to board where it boards
	 * ({@link SailingFleet#cheapestAt}), or {@code null}.
	 */
	public static SailingFleet.Boat boat(Transport transport, SailingFleet fleet)
	{
		SailingVessel.Kind kind = SailingVessel.Kind.ofTransport(transport.getType());
		SailingMooring from = from(transport), to = to(transport);
		if (kind == null || from == null || to == null) return null;
		return fleet.cheapestAt(from, kind);
	}

	/**
	 * Whether {@code transport}'s time at {@code vessel}'s speed is how long the boat takes: the leg was timed at that
	 * speed, and the boat has the parts for the areas it sails through there. Otherwise its duration for the boat
	 * ({@link #boundFor}) only bounds it.
	 */
	public static boolean timedFor(Transport transport, SailingVessel vessel)
	{
		LegTimes times = transport.getLegTimes();
		int speed = LegTimes.index(vessel.speed());
		return times != null && speed >= 0 && times.ticks(speed) != LegTimes.NONE
			&& vessel.areas().containsAll(times.areas(speed));
	}

	/**
	 * Whether {@code vessel} may be able to sail {@code transport}: not when the leg was timed at the boat's speed and
	 * no boat of its kind, even with every part, can sail it at that speed.
	 */
	static boolean sailable(Transport transport, SailingVessel vessel)
	{
		LegTimes times = transport.getLegTimes();
		int speed = LegTimes.index(vessel.speed());
		return times == null || speed < 0 || times.ticks(speed) != LegTimes.NONE;
	}

	/**
	 * {@code transport} with a duration no more than {@code vessel} takes. At a speed the leg was timed at it is the
	 * time at that speed: with fewer parts a lower bound, since keeping out of water only makes a leg longer. At any
	 * other speed the moves themselves change (each tick's velocity is rounded to quarter tiles), so no timed speed
	 * says anything sure about the boat's; the bound is then the straight line between the berths, less the docking
	 * range at each end (the boat casts off and docks within it), at the boat's top speed, as for every other leg
	 * sailed for a query.
	 */
	public static Transport boundFor(Transport transport, SailingVessel vessel)
	{
		LegTimes times = transport.getLegTimes();
		int speed = LegTimes.index(vessel.speed());
		if (times != null && speed >= 0 && times.ticks(speed) != LegTimes.NONE)
			return times.ticks(speed) == transport.getDuration() ? transport : transport.withDuration(times.ticks(speed));
		SailingMooring from = from(transport), to = to(transport);
		double tiles = Tiles.distance(from.berthTile(), to.berthTile());
		int sailed = (int) Math.floor(Math.max(0, tiles - 2 * SailingMooring.DOCKING_RANGE) / vessel.moves().topSpeed());
		return transport.withDuration(SailingMooring.BOARD_TICKS + sailed + SailingMooring.DISEMBARK_TICKS);
	}

	/** What the files are made from: the collision map, the moorings, the speeds and the search's rules. */
	public static String fingerprint(List<SailingMooring> moorings)
	{
		return fingerprint(readBytes("/collision-map.zip"), moorings);
	}

	/**
	 * What the sailing data is made from, in short: the collision map {@code zip} but for its sailing layer (which is
	 * made from it), the moorings, and the speeds and version of the search that times the legs.
	 */
	public static String fingerprint(byte[] zip, List<SailingMooring> moorings)
	{
		CRC32 crc = new CRC32();
		SortedMap<String, byte[]> entries = new TreeMap<>();
		try (ZipInputStream in = new ZipInputStream(new ByteArrayInputStream(zip)))
		{
			ZipEntry entry;
			while ((entry = in.getNextEntry()) != null)
			{
				if (!entry.isDirectory() && !entry.getName().startsWith(SailingWaters.LAYER + "/"))
					entries.put(entry.getName(), in.readAllBytes());
			}
		}
		catch (IOException e)
		{
			throw new UncheckedIOException(e);
		}
		for (Map.Entry<String, byte[]> entry : entries.entrySet())
		{
			crc.update(entry.getKey().getBytes(StandardCharsets.UTF_8));
			crc.update(entry.getValue());
		}
		StringBuilder data = new StringBuilder();
		for (SailingMooring mooring : moorings)
		{
			data.append(mooring.name()).append(mooring.landTile()).append(mooring.berthTile())
				.append(mooring.vessels()).append(mooring.requirements().getSkillLevels())
				.append(mooring.requirements().getQuests()).append('\n');
		}
		data.append(SailingMooring.BOARD_TICKS).append(' ').append(SailingMooring.DISEMBARK_TICKS).append(' ')
			.append(SailingMooring.DOCKING_RANGE);
		crc.update(data.toString().getBytes(StandardCharsets.UTF_8));
		StringBuilder speeds = new StringBuilder();
		for (int i = 0; i < LegTimes.SPEEDS.length; i++)
			speeds.append(i == 0 ? "" : ",").append(BoatSpeed.tilesPerTick(LegTimes.SPEEDS[i]));
		return Long.toHexString(crc.getValue()) + " speeds " + speeds + " search " + SEARCH_VERSION;
	}

	/** The fingerprint a transport file was made with, or {@code null}. */
	static String fingerprintOf(String contents)
	{
		for (String line : contents.split("\n"))
		{
			if (line.startsWith(FINGERPRINT)) return line.substring(FINGERPRINT.length()).trim();
		}
		return null;
	}

	static byte[] readBytes(String path)
	{
		try (InputStream in = SailingTransports.class.getResourceAsStream(path))
		{
			if (in == null) throw new IllegalStateException("missing " + path);
			return in.readAllBytes();
		}
		catch (IOException error)
		{
			throw new IllegalStateException("cannot read " + path, error);
		}
	}
}
